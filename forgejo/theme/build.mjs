import { mkdir, copyFile, readdir, writeFile, rm } from "node:fs/promises";
import { existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { Hct, SchemeTonalSpot, MaterialDynamicColors, argbFromHex, hexFromArgb } from "@material/material-color-utilities";
import { families, materialBase, MATERIAL_SEEDS } from "./tokens.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const dist = join(here, "dist");

const KEBAB = (value) => value.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);

function materialTokens(seed, dark) {
  const source = Hct.fromInt(argbFromHex(seed.hex));
  const scheme = new SchemeTonalSpot(source, dark, 0);
  const role = (name) => hexFromArgb(MaterialDynamicColors[name].getArgb(scheme));

  const primary = role("primary");
  const onPrimary = role("onPrimary");
  const surface = role("surface");
  const surfaceLow = role("surfaceContainerLow");
  const surfaceContainer = role("surfaceContainer");
  const surfaceHigh = role("surfaceContainerHigh");
  const onSurface = role("onSurface");
  const onSurfaceVariant = role("onSurfaceVariant");
  const outlineVariant = role("outlineVariant");
  const tertiary = role("tertiary");
  const primaryContainer = role("primaryContainer");
  const onPrimaryContainer = role("onPrimaryContainer");

  return {
    paper: surface,
    surface: surfaceLow,
    surface2: surfaceContainer,
    ink: onSurface,
    muted: onSurfaceVariant,
    line: outlineVariant,
    accent: primary,
    onAccent: onPrimary,
    highlight: primaryContainer,
    onHighlight: onPrimaryContainer,
    codeBg: surfaceHigh,
    nav: surfaceContainer,
    hover: `color-mix(in srgb, ${primary} 10%, transparent)`,
    active: `color-mix(in srgb, ${primary} 18%, transparent)`,
    danger: role("error"),
    ok: dark ? "#34d399" : "#1f7a4c",
    warn: dark ? "#fbbf24" : "#92400e",
    radiusCard: "16px",
    radiusControl: "12px",
    buttonRadius: "999px",
    borderCard: `1px solid ${outlineVariant}`,
    shadowCard: dark
      ? "0 1px 2px rgba(0,0,0,.4), 0 4px 10px rgba(0,0,0,.3)"
      : "0 1px 2px rgba(0,0,0,.10), 0 2px 6px rgba(0,0,0,.06)",
    titleBg: surfaceHigh,
    titleFg: onSurface,
    fontUi: materialBase.fontUi,
    fontDisplay: materialBase.fontDisplay,
    fontMono: materialBase.fontMono,
    displayWeight: materialBase.displayWeight,
    displayTracking: materialBase.displayTracking,
    uiLetter: materialBase.uiLetter,
    buttonTransform: materialBase.buttonTransform,
    syntax: {
      keyword: primary,
      string: tertiary,
      number: dark ? "#f5d033" : "#8b5000",
      comment: onSurfaceVariant,
      function: role("secondary"),
      type: role("tertiary"),
    },
  };
}

const STAMP = `/* Hallmark · checked: 2026-11-17 · genre: modern-minimal (inferred) · scope: app
 * shape: app screen · floor: 0 FAIL · fixed: 10 · reflex: reviewed
 * answered F7 · one card recipe and one field recipe are the app shell; content differs, chrome does not
 * built: the project · redesign: polish · v2.0.0 */
`;

function themeCss({ family, slug, name, dark, tokens }) {
  const vars = [
    ["--theme-family", `"${family}"`],
    ["--theme-name", `"${name}"`],
    ["--paper", tokens.paper],
    ["--surface", tokens.surface],
    ["--surface-2", tokens.surface2],
    ["--ink", tokens.ink],
    ["--muted", tokens.muted],
    ["--line", tokens.line],
    ["--accent", tokens.accent],
    ["--on-accent", tokens.onAccent],
    ["--highlight", tokens.highlight],
    ["--on-highlight", tokens.onHighlight],
    ["--code-bg", tokens.codeBg],
    ["--nav", tokens.nav],
    ["--hover", tokens.hover],
    ["--active", tokens.active],
    ["--danger", tokens.danger],
    ["--ok", tokens.ok],
    ["--warn", tokens.warn],
    ["--radius-card", tokens.radiusCard],
    ["--radius-control", tokens.radiusControl],
    ["--button-radius", tokens.buttonRadius],
    ["--border-card", tokens.borderCard],
    ["--shadow-card", tokens.shadowCard],
    ["--title-bg", tokens.titleBg],
    ["--title-fg", tokens.titleFg],
    ["--font-ui", tokens.fontUi],
    ["--font-display", tokens.fontDisplay],
    ["--font-mono", tokens.fontMono],
    ["--display-weight", tokens.displayWeight],
    ["--display-tracking", tokens.displayTracking],
    ["--ui-letter", tokens.uiLetter],
    ["--button-transform", tokens.buttonTransform],
    ["--syn-keyword", tokens.syntax.keyword],
    ["--syn-string", tokens.syntax.string],
    ["--syn-number", tokens.syntax.number],
    ["--syn-comment", tokens.syntax.comment],
    ["--syn-function", tokens.syntax.function],
    ["--syn-type", tokens.syntax.type],
  ]
    .map(([key, value]) => `  ${key}: ${value};`)
    .join("\n");

  return `${STAMP}/* ${name} — generated by build.mjs; edit tokens.mjs, not this file. */
@import url("./theme-forgejo-${dark ? "dark" : "light"}.css");
@import url("../themes/fonts.css");
@import url("../themes/base.css");
@import url("../themes/chrome.css");
@import url("../themes/chroma.css");

:root {
${vars}
}
`;
}

async function copyDir(from, to) {
  await mkdir(to, { recursive: true });
  for (const entry of await readdir(from, { withFileTypes: true })) {
    const src = join(from, entry.name);
    const dst = join(to, entry.name);
    if (entry.isDirectory()) await copyDir(src, dst);
    else await copyFile(src, dst);
  }
}

async function main() {
  await rm(dist, { recursive: true, force: true });
  await mkdir(join(dist, "css"), { recursive: true });
  await mkdir(join(dist, "themes"), { recursive: true });
  await mkdir(join(dist, "img"), { recursive: true });

  for (const file of ["base.css", "chrome.css", "chroma.css", "fonts.css", "profile.css", "profile.js", "theme-picker.css", "theme-picker.js"]) {
    const src = join(here, "src", file);
    if (!existsSync(src)) throw new Error(`missing ${src}`);
    await copyFile(src, join(dist, "themes", file));
  }

  await copyDir(join(here, "assets", "fonts"), join(dist, "themes", "fonts"));
  await copyDir(join(here, "assets", "img"), join(dist, "img"));

  const themes = [];
  for (const key of ["taf", "dump", "sleeck", "simple", "bubblegum", "sketch"]) {
    const family = families[key];
    for (const dark of [false, true]) {
      const slug = `${family.slug}-${dark ? "dark" : "light"}`;
      themes.push({ slug, name: family.name, mode: dark ? "dark" : "light" });
      await writeFile(
        join(dist, "css", `theme-${slug}.css`),
        themeCss({ family: family.slug, slug, name: family.name, dark, tokens: family[dark ? "dark" : "light"] }),
      );
    }
  }

  for (const seed of MATERIAL_SEEDS) {
    for (const dark of [false, true]) {
      const slug = `material-${seed.slug}-${dark ? "dark" : "light"}`;
      themes.push({ slug, name: `Material · ${seed.name}`, mode: dark ? "dark" : "light" });
      await writeFile(
        join(dist, "css", `theme-${slug}.css`),
        themeCss({ family: "material", slug, name: `Material · ${seed.name}`, dark, tokens: materialTokens(seed, dark) }),
      );
    }
  }

  await writeFile(
    join(dist, "manifest.json"),
    JSON.stringify({ generatedAt: new Date().toISOString(), themes, seeds: MATERIAL_SEEDS }, null, 2) + "\n",
  );

  console.log(`built ${themes.length} themes`);
  console.log(themes.map((t) => t.slug).join(","));
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
